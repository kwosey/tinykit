import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { generateStory } from '../src/stories/grammar'

test('discover, lock, mutate, direct and keep a story across reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#tiny-scenes')
  const family = page.locator('.title h2')
  const first = await family.textContent()
  const beats = page.getByRole('list', { name: 'Story beats' })
  const moments = beats.getByRole('listitem')
  await expect(moments).toHaveCount(3)
  await expect(page.getByRole('complementary', { name: 'Scene tools' })).toHaveCount(0)
  const canvas = page.getByLabel('Scene preview')
  await expect(canvas).toBeVisible()
  const firstFrame = await canvas.evaluate(element => (element as HTMLCanvasElement).toDataURL())
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(async () => Number(await page.getByRole('slider', { name: 'Scrub' }).inputValue())).toBeGreaterThan(0.05)
  await page.getByRole('button', { name: 'Pause' }).click()
  const initialBeat = Number(await moments.nth(1).locator('small').textContent().then(value => value?.replace(' s', '')))
  await page.getByRole('slider', { name: 'Scrub' }).fill(String(initialBeat + 0.75))
  const firstMotion = await canvas.evaluate(element => (element as HTMLCanvasElement).toDataURL())
  expect(firstMotion).not.toBe(firstFrame)
  await page.getByRole('button', { name: 'Restart' }).click()
  expect(await canvas.evaluate(element => (element as HTMLCanvasElement).toDataURL())).toBe(firstFrame)

  await page.getByRole('button', { name: 'Another Story' }).click()
  await expect(family).not.toHaveText(first!)
  const second = (await family.textContent())!
  const labels = await beats.locator('strong').allTextContents()
  await page.getByRole('button', { name: 'Lock Setup' }).click()
  await page.getByRole('button', { name: 'Lock Event' }).click()
  await page.getByRole('button', { name: 'Mutate', exact: true }).click()
  await expect(family).toHaveText(second)
  const variation = await beats.locator('strong').allTextContents()
  expect(variation.slice(0, 2)).toEqual(labels.slice(0, 2))
  expect(variation[2]).not.toEqual(labels[2])
  await page.getByRole('button', { name: 'Keep', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Added to your collection')
  await page.getByRole('button', { name: 'Keep', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('already in your collection')
  await page.getByRole('button', { name: 'Lock Outcome' }).click()
  await page.getByRole('button', { name: 'Mutate', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Unlock Outcome')
  expect(await beats.locator('strong').allTextContents()).toEqual(variation)
  await page.getByRole('button', { name: 'Lock Outcome' }).click()

  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Direct a beat' })).toBeVisible()
  const ending = page.getByLabel('Ending', { exact: true })
  const current = Number(await ending.inputValue())
  await ending.selectOption(String((current + 1) % 4))
  await expect(moments.last().locator('strong')).not.toHaveText(variation[2])

  const jsonWait = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON' }).click()
  const exported = await readFile((await (await jsonWait).path())!)
  const data = JSON.parse(exported.toString())
  expect(data.version).toBe(2)
  expect(data.beats.map((beat: { locked: boolean }) => beat.locked)).toEqual([true, true, true])

  await page.getByRole('button', { name: 'Another Story' }).click()
  await expect(family).not.toHaveText(second)
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(family).toHaveText(second)
  await page.getByRole('button', { name: 'Redo' }).click()
  const latest = (await family.textContent())!
  await page.reload()
  await expect(family).toHaveText(latest)
  await page.getByRole('button', { name: /Collection/ }).click()
  await page.getByRole('button', { name: 'Open ' + second }).click()
  await expect(family).toHaveText(second)
  expect(await beats.locator('strong').allTextContents()).toEqual(variation)
  await expect(page.getByRole('button', { name: 'Lock Setup' })).toHaveAttribute('aria-pressed', 'true')

  await page.getByRole('button', { name: /Collection/ }).click()
  await page.getByRole('button', { name: 'Delete ' + second }).click()
  await expect(page.getByText('Use Keep to save a version here.')).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Import scene file').setInputFiles({ name: 'story.json', mimeType: 'application/json', buffer: exported })
  await expect(page.getByRole('status')).toHaveText('Story imported')
  await expect(moments.last().locator('strong')).not.toHaveText(variation[2])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})


test('directs the cast and timing while protecting manually assigned motion', async ({ page }) => {
  await page.addInitScript(story => {
    if (!localStorage.getItem('tinykit.scenes.v2.draft')) localStorage.setItem('tinykit.scenes.v2.draft', JSON.stringify(story))
  }, generateStory(42, 'meeting'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#tiny-scenes')
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Add object' }).click()
  const added = await page.getByLabel('Selected object').inputValue()
  await page.getByRole('combobox', { name: 'Beat', exact: true }).selectOption('0')
  await page.getByRole('combobox', { name: 'Lead', exact: true }).selectOption(added)
  await expect(page.getByRole('status')).toHaveText('Cast updated.')
  await page.getByRole('combobox', { name: 'Beat', exact: true }).selectOption('1')
  await page.getByRole('slider', { name: 'Beat time (s)' }).fill('1.5')
  await expect(page.getByRole('list', { name: 'Story beats' }).getByRole('listitem').nth(1)).toContainText('1.5 s')
  await page.getByRole('combobox', { name: 'Action' }).selectOption('Float')
  await page.getByRole('button', { name: 'Mutate', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('manual cast motion protect this ending')
  await page.reload()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Selected object').selectOption(added)
  await expect(page.getByRole('combobox', { name: 'Action' })).toHaveValue('Float')
  await page.getByRole('button', { name: 'Restore story motion' }).click()
  await page.getByRole('button', { name: 'Mutate', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('New ending')
})
