import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { presets } from '../src/forms/model'

test('plays, tunes, keeps and round-trips a Form Lab composition', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Form Lab' })).toBeVisible()
  const canvas = page.getByLabel('Composition canvas')
  const frame = () => canvas.evaluate(element => (element as HTMLCanvasElement).toDataURL())
  const opening = await frame()
  const scrub = page.getByRole('slider', { name: 'Scrub' })
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(async () => Number(await scrub.inputValue())).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Pause' }).click()
  await expect.poll(frame).not.toBe(opening)
  await page.getByRole('button', { name: 'Restart' }).click()
  await expect.poll(frame).toBe(opening)
  await scrub.fill('3')
  await expect.poll(frame).not.toBe(opening)
  const before = await frame()
  const energy = page.getByRole('slider', { name: 'Energy' })
  await energy.fill('90')
  await expect.poll(frame).not.toBe(before)
  await page.getByRole('button', { name: 'Lock Energy' }).click()
  await page.getByRole('button', { name: 'Mutate' }).click()
  await expect(energy).toHaveValue('90')
  await page.getByRole('button', { name: 'Undo' }).click()
  await page.getByRole('button', { name: 'Redo' }).click()
  await page.getByRole('button', { name: 'Keep', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Kept in Collection.')
  await page.getByRole('button', { name: 'Next Composition' }).click()
  await expect(page.locator('.form-heading p')).not.toContainText('Orbit')
  await page.reload()
  await expect(page.locator('.form-heading p')).not.toContainText('Orbit')
  await page.getByRole('button', { name: /Collection/ }).click()
  await page.getByRole('button', { name: 'Open Orbit' }).click()
  await expect(energy).toHaveValue('90')
  await expect(page.getByRole('button', { name: 'Lock Energy' })).toHaveAttribute('aria-pressed', 'true')

  await page.getByText('More settings', { exact: true }).click()
  await scrub.fill('3')
  await expect.poll(frame).not.toBe(opening)
  const expected = await frame()
  const pngReady = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export PNG' }).click()
  const png = await readFile((await (await pngReady).path())!)
  expect(png.readUInt32BE(16)).toBe(960)
  expect(png.readUInt32BE(20)).toBe(600)
  expect('data:image/png;base64,' + png.toString('base64')).toBe(expected)
  const jsonReady = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON' }).click()
  const json = await readFile((await (await jsonReady).path())!)
  await page.getByRole('button', { name: 'Next Composition' }).click()
  const importer = page.getByLabel('Import composition file')
  await importer.setInputFiles({ name: 'form.json', mimeType: 'application/json', buffer: json })
  await expect(energy).toHaveValue('90')
  await importer.setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(page.getByRole('status')).toContainText('Invalid Form Lab JSON')
  await expect(energy).toHaveValue('90')

  await page.getByRole('checkbox', { name: 'Loop' }).uncheck()
  await scrub.fill('11.85')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(scrub).toHaveValue('12')
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Loop' }).check()
  await scrub.fill('11.9')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(async () => Number(await scrub.inputValue())).toBeLessThan(8)
  await page.getByRole('button', { name: 'Pause' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('renders every preset and keeps both experiments independently accessible', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByText('More settings', { exact: true }).click()
  const selector = page.getByRole('combobox', { name: 'Starting composition' })
  const canvas = page.getByLabel('Composition canvas')
  const frames = new Set<string>()
  for (let i = 0; i < presets.length; i++) {
    await selector.selectOption(String(i))
    await expect(page.locator('.form-heading p')).toContainText(presets[i].name)
    await page.getByRole('slider', { name: 'Scrub' }).fill('3')
    const sample = () => canvas.evaluate(element => (element as HTMLCanvasElement).toDataURL())
    await expect.poll(async () => frames.has(await sample())).toBe(false)
    frames.add(await sample())
  }
  expect(frames.size).toBe(presets.length)
  await page.getByRole('link', { name: 'Tiny Scenes' }).click()
  await expect(page.getByRole('heading', { name: 'Tiny Scenes' })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Story beats' })).toBeVisible()
  await page.getByRole('link', { name: 'Form Lab' }).click()
  await expect(page.locator('.form-heading p')).toContainText('Breathing Grid')
  expect(await page.evaluate(() => Boolean(localStorage.getItem('tinykit.scenes.v2.draft')) &&
    Boolean(localStorage.getItem('tinykit.form-lab.v1.draft')))).toBe(true)
  expect(errors).toEqual([])
})
